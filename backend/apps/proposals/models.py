from django.db import models
from apps.common.models import BaseModel
from apps.leads.models import Lead

class Proposal(BaseModel):
    STATUS_CHOICES = [
        ('DRAFT', 'AI Draft Generated'),
        ('UNDER_REVIEW', 'Human Review In Progress'),
        ('APPROVED', 'Human Approved (Ready to Dispatch)'),
        ('REJECTED', 'Changes Requested / Rejected'),
        ('SENT', 'Sent to Prospect'),
    ]

    lead = models.ForeignKey(Lead, on_delete=models.CASCADE, related_name='proposals')
    title = models.CharField(max_length=255)
    status = models.CharField(max_length=50, choices=STATUS_CHOICES, default='UNDER_REVIEW')
    total_amount = models.DecimalField(max_digits=12, decimal_places=2, default=145000.00)
    currency = models.CharField(max_length=10, default='USD')
    version = models.CharField(max_length=20, default='v1.0')
    
    # Proposal content generated by RAG + LLM
    executive_summary = models.TextField()
    scope_of_work = models.TextField()
    deliverables = models.JSONField(default=list, blank=True)
    pricing_breakdown = models.JSONField(default=list, blank=True)
    rag_sources = models.JSONField(default=list, blank=True, help_text="Retrieved enterprise reference docs & confidence")
    
    # Human-in-the-loop review fields
    reviewed_by = models.CharField(max_length=150, blank=True, default='E. Vance (RevOps Dir)')
    reviewer_notes = models.TextField(blank=True, default='')
    reviewed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.title} - {self.lead.company_name} [{self.status}]"
